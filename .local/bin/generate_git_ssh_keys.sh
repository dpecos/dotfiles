#!/usr/bin/env bash

set -euo pipefail

HOSTNAME="$(uname -n | sed 's/\.local$//')"
SSH_DIR="$HOME/.ssh"
ZSH_LOCAL="$HOME/.zshrc.pre.local"

mkdir -p "$SSH_DIR"
chmod 700 "$SSH_DIR"

# Git hosting services
declare -A SERVICES=(
  [github]="github.com"
  [gitlab]="gitlab.com"
  [forgejo]="code.dplabs.dev"
)

declare -A KEY_NAMES=(
  [github]="id_ed25519_${HOSTNAME}_github"
  [gitlab]="id_ed25519_${HOSTNAME}_gitlab"
  [forgejo]="id_ed25519_${HOSTNAME}_forgejo"
)

declare -A ADD_URLS=(
  [github]="https://github.com/settings/ssh/new"
  [gitlab]="https://gitlab.com/-/user_settings/ssh_keys"
  [forgejo]="https://code.dplabs.dev/user/settings/keys"
)

copy_to_clipboard() {
  local file="$1"

  if command -v pbcopy >/dev/null 2>&1; then
    pbcopy <"$file"
  elif command -v wl-copy >/dev/null 2>&1; then
    wl-copy <"$file"
  elif command -v xclip >/dev/null 2>&1; then
    xclip -selection clipboard <"$file"
  elif command -v xsel >/dev/null 2>&1; then
    xsel --clipboard --input <"$file"
  else
    echo "ERROR: No clipboard utility found."
    echo "Install pbcopy (macOS), wl-copy, xclip, or xsel."
    exit 1
  fi
}

open_url() {
  local url="$1"

  if command -v open >/dev/null 2>&1; then
    open "$url"
  elif command -v xdg-open >/dev/null 2>&1; then
    xdg-open "$url" >/dev/null 2>&1 &
  else
    echo "Open this URL manually:"
    echo "$url"
  fi
}

echo
echo "SSH key setup"
echo "============="
echo
echo "Hostname: $HOSTNAME"
echo "SSH dir:  $SSH_DIR"
echo

GENERATED_KEYS=()

for service in github gitlab forgejo; do
  key_name="${KEY_NAMES[$service]}"
  key_file="$SSH_DIR/$key_name"
  pub_file="${key_file}.pub"

  echo "----------------------------------------"
  echo "Setting up $service"
  echo "----------------------------------------"

  if [[ -f "$key_file" ]]; then
    echo "Key already exists:"
    echo "  $key_file"
  else
    echo "Generating key:"
    echo "  $key_file"

    ssh-keygen \
      -t ed25519 \
      -C "${HOSTNAME}-${service}" \
      -f "$key_file" \
      -N ""

    chmod 600 "$key_file"
    chmod 644 "$pub_file"

    echo "Key generated."
  fi

  GENERATED_KEYS+=("$key_name")

  echo
  echo "Copying public key to clipboard..."
  copy_to_clipboard "$pub_file"

  echo "Public key copied to clipboard."
  echo
  echo "Opening:"
  echo "  ${ADD_URLS[$service]}"
  echo

  open_url "${ADD_URLS[$service]}"

  read -r -p "Press ENTER after you have added the $service SSH key..."

  echo
  echo "$service key confirmed."
  echo
done

# ------------------------------------------------------------
# Configure OMZ identities
# ------------------------------------------------------------

echo "----------------------------------------"
echo "Configuring OMZ identities"
echo "----------------------------------------"

touch "$ZSH_LOCAL"

# Remove a previously generated block, if present.
if grep -q "# BEGIN dplabs SSH identities" "$ZSH_LOCAL" 2>/dev/null; then
  echo "Removing existing dplabs SSH identities configuration..."

  sed -i.bak \
    '/# BEGIN dplabs SSH identities/,/# END dplabs SSH identities/d' \
    "$ZSH_LOCAL"

  rm -f "${ZSH_LOCAL}.bak"
fi

{
  echo
  echo "# BEGIN dplabs SSH identities"
  echo "# Generated by ssh-hosting-keys"
  echo "zstyle :omz:plugins:ssh-agent identities \\"
  for i in "${!GENERATED_KEYS[@]}"; do
    key="${GENERATED_KEYS[$i]}"

    if [[ "$i" -lt "$((${#GENERATED_KEYS[@]} - 1))" ]]; then
      echo "  $key \\"
    else
      echo "  $key"
    fi
  done
  echo "zstyle :omz:plugins:ssh-agent lifetime 4h"
  echo "# END dplabs SSH identities"
} >>"$ZSH_LOCAL"

echo
echo "Added OMZ SSH identities to:"
echo "  $ZSH_LOCAL"
echo

echo "Done!"
echo
echo "Generated identities:"
for key in "${GENERATED_KEYS[@]}"; do
  echo "  ~/.ssh/$key"
done

echo
echo "Reload your shell with:"
echo "  source ~/.zshrc"
echo
